const LanguageContext = createContext(null);

const format = (template, values = {}) =>
  String(template).replace(/\{(\w+)\}/g, (_, key) => values[key] ?? "");

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => localStorage.getItem(LANGUAGE_KEY) || "en");

  useEffect(() => {
    document.documentElement.lang = language;
    localStorage.setItem(LANGUAGE_KEY, language);
  }, [language]);

  const value = useMemo(() => {
    const setLanguage = (nextLanguage) => setLanguageState(nextLanguage === "vi" ? "vi" : "en");
    const toggleLanguage = () => setLanguageState((previous) => (previous === "en" ? "vi" : "en"));
    const t = (key, values) => format(translations[language]?.[key] || translations.en[key] || key, values);
    return { language, setLanguage, toggleLanguage, t };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }
  return context;
}

export function LanguageToggle({ className = "" }) {
  const { language, setLanguage } = useLanguage();

  return (
    <div className={`inline-flex rounded-full border border-line bg-white/85 p-1 shadow-glass backdrop-blur-xl ${className}`}>
      {[
        ["en", "EN"],
        ["vi", "VI"],
      ].map(([value, label]) => (
        <button
          key={value}
          type="button"
          onClick={() => setLanguage(value)}
          className={`rounded-full px-3 py-1.5 text-xs font-black transition ${
            language === value ? "bg-rose text-white" : "text-muted hover:bg-white hover:text-ink"
          }`}
        >
          {label}
        </button>
      ))}
    </div>
  );
}

export function FloatingLanguageToggle() {
  return (
    <div className="fixed bottom-5 right-5 z-[70]">
      <LanguageToggle />
    </div>
  );
}
